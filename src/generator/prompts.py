def build_shield_prompt(
    incoming_text: str,
    context: Dict[str, Any],
    stage: str = "In_DM",
    deposit_est: str = "500_2000"
) -> str:
    """Builds prompt for DM objection shield with strict stage binding."""
    chapter = context.get("chapter") or {}
    card = context.get("battlecard") or {}
    bridge_instruction = STAGE_BRIDGES.get(stage, STAGE_BRIDGES["In_DM"])

    kb_facts = []
    if card:
        kb_facts.append(f"СУТЬ ОТВЕТА НА ВОЗРАЖЕНИЕ:\n{card.get('answer')}")
    if chapter.get("layer4_unit_econ_scaled"):
        kb_facts.append(f"UNIT-ЭКОНОМИКА (ПОД ДЕПОЗИТ ${deposit_est}):\n{chapter['layer4_unit_econ_scaled']}")
    if chapter.get("layer5_script"):
        kb_facts.append(f"ПРИМЕР ДИАЛОГА:\n{chapter['layer5_script']}")

    kb_context_str = "\n\n".join(kb_facts)

    stage_specific_rules = ""
    if stage == "In_DM":
        stage_specific_rules = """
КРИТИЧЕСКОЕ ПРАВИЛО СТАДИИ In_DM:
- КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО предлагать тест на $20, упоминать $20, +$0.70 или любые проверки!
- Сначала ответь на сомнение собеседника 1-2 сухими техническими предложениями из базы знаний.
- Закончи ТОЛЬКО квалифицирующим вопросом: «На какой бирже сам в основном торгуешь — Bybit, OKX? Руками разницу стаканов пробовал забирать или чисто фьючи?»"""
    elif stage == "Legend_&_Media":
        stage_specific_rules = """
ПРАВИЛО СТАДИИ Legend_&_Media:
- Объясни механику фермы б/у iPhone ($150–$200), аппаратный чип Apple Secure Enclave (App Attest) против антидетектов и лимит 4 круга в сутки перед холдом T+1.
- Спроси, готов ли увидеть видео/скрин разницы стаканов."""
    elif stage == "Test_20":
        stage_specific_rules = """
ПРАВИЛО СТАДИИ Test_20:
- Закрывай на проверочный прогон $20–$30 со своего счета Bybit/OKX под своей 2FA за 10 минут (+$0.70 чистыми без передачи средств)."""

    return f"""СООБЩЕНИЕ ЛИДА В ЛС:
«{incoming_text}»

ТЕКУЩИЙ ЭТАП: {stage}
ДЕПОЗИТ ЛИДА: ${deposit_est}

БАЗА ЗНАНИЙ И МАТЕМАТИКА:
{kb_context_str}

ЦЕЛЬ ЗАКРЫТИЯ (МОСТИК):
{bridge_instruction}
{stage_specific_rules}

ЗАДАЧА:
Напиши ответ сейлз-клоузера в ЛС.

ПРАВИЛА:
1. Длина: строго 3–4 коротких предложения (до 90–120 токенов).
2. Общение строго на «ты».
3. ЗАПРЕЩЕНО упоминать HFT-софт, роботов или подключение к конвейеру.
4. ЗАПРЕЩЕНО просить «скрин баланса», «показать кошелек» или скриншоты.
5. Без литературщины и ChatGPT-клише («при всем уважении», «биология против кремния»). Спокойный уверенный практик."""
